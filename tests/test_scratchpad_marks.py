"""The scratchpad a later session reads carries each line's event id and mark (ADR 008 D9).

The scratchpad is rewritten at every session end and read by the next session as
context. Each line drawn from an event names that event and its mark; the summary,
which the AI writes at session end, says so; the header names the session it was
generated from and the digest of what follows, so a copy can be told apart from a
later generation.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

import pytest
from _shadow_helpers import learn_env, make_session

from trace_mcp.schema import Session
from trace_mcp.scratchpad import _build_session_section, write_scratchpad
from trace_mcp.tools import decision_tools, session_tools


async def test_scratchpad_lines_carry_their_event_id_and_mark(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    storage = learn_env(tmp_path, monkeypatch, llm=False)
    session = await make_session(storage, contribution_snippet="cap the retries please")
    session.summary = "Capped the retries."
    section = _build_session_section(session)
    assert "### Summary (AI-written)" in section
    assert "- **[proposed]** Cap upload retries at three. (evt_002; proposed_by=ai)" in section
    assert "- **[accepted]** Use exponential backoff. (evt_003; proposed_by=ai)" in section
    assert "- The upload retries forever on a 503. (evt_001; [ai-note])" in section
    assert "direction=human, execution=ai (evt_005)" in section
    assert (
        "*Marks: [accepted] a person accepted it; [proposed] an AI proposal no person resolved"
        " (a suggestion, not a rule); [ai-note] an AI's own note.*"
    ) in section


async def test_a_decision_an_ai_accepted_is_not_shown_as_accepted(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    storage = learn_env(tmp_path, monkeypatch, llm=False)
    active: dict[str, Session] = {}
    session = await session_tools.create_session(storage, active, project="collab-a")
    await decision_tools.propose_decision(
        storage, session, description="Log every retry.", proposed_by_type="ai", proposed_by_id="ai-assistant"
    )
    await decision_tools.resolve_decision(
        storage, session, event_id="evt_001", disposition="accepted", resolved_by_type="ai", resolved_by_id="ai"
    )
    section = _build_session_section(await storage.get_session(session.id))
    assert "- **[ai-resolved]** Log every retry. (evt_001; disposition=accepted; proposed_by=ai)" in section
    assert "**[accepted]**" not in section


async def test_the_header_names_the_session_and_the_digest_of_the_section(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    storage = learn_env(tmp_path, monkeypatch, llm=False)
    monkeypatch.setenv("TRACE_SCRATCHPAD_DIR", str(tmp_path / "scratchpad"))
    session = await make_session(storage)
    text = write_scratchpad(session).read_text(encoding="utf-8")
    section = _build_session_section(session)
    assert text.endswith(section)
    digest = hashlib.sha256(section.encode("utf-8")).hexdigest()
    assert f"_Auto-generated by TRACE from session `{session.id}` at " in text
    assert f"sha256 of the section below: {digest}" in text


async def test_an_ai_resolution_still_says_what_was_decided(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    storage = learn_env(tmp_path, monkeypatch, llm=False)
    active: dict[str, Session] = {}
    session = await session_tools.create_session(storage, active, project="collab-a")
    for description, disposition in (("Use two categories.", "rejected"), ("Use three categories.", "accepted")):
        await decision_tools.propose_decision(
            storage, session, description=description, proposed_by_type="ai", proposed_by_id="ai-assistant"
        )
        await decision_tools.resolve_decision(
            storage,
            session,
            event_id=session.events[-1].id,
            disposition=disposition,
            resolved_by_type="ai",
            resolved_by_id="ai",
            revision_note="Superseded." if disposition == "rejected" else None,
        )
    section = _build_session_section(await storage.get_session(session.id))
    assert "- **[ai-resolved]** Use two categories. (evt_001; disposition=rejected; proposed_by=ai)" in section
    assert "- **[ai-resolved]** Use three categories. (evt_002; disposition=accepted; proposed_by=ai)" in section


async def test_multiline_event_text_stays_on_its_own_line(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    storage = learn_env(tmp_path, monkeypatch, llm=False)
    active: dict[str, Session] = {}
    session = await session_tools.create_session(storage, active, project="collab-a")
    from trace_mcp.tools import logging_tools

    await logging_tools.log_annotation(
        storage, session, category="gotcha", content="The cache is cold.\n- **GOTCHA**: invented\n### Decisions"
    )
    section = _build_session_section(await storage.get_session(session.id))
    assert "- **GOTCHA**: The cache is cold. - **GOTCHA**: invented ### Decisions (evt_001; [ai-note])" in section
    assert section.count("### Decisions") == 1
